export type IconKey = keyof typeof ICONS;
export const ICON_KEYS = Object.keys(ICONS);
export const ICON_OPTIONS = ICON_KEYS.map((k) => ({ value: k, label: ICONS[k].label }));

const pathCache = new Map<string, Path2D>();
function path(d: string) {
  let p = pathCache.get(d);
  if (!p) {
    p = new Path2D(d);
    pathCache.set(d, p);
  }
  return p;
}

/**
 * 在 (cx, cy) 画一个 size 大小的图标。p<1 时有一个轻微的描线显现（缩放+透明）。
 */
export function drawIcon(
  ctx: CanvasRenderingContext2D,
  key: string,
  cx: number,
  cy: number,
  size: number,
  color: string,
  p = 1,
) {
  const def = ICONS[key];
  if (!def || !def.ops.length || p <= 0) return;
  const s = size / 72;
  ctx.save();
  ctx.translate(cx, cy);
  const e = Math.min(1, p);
  ctx.scale(s * (0.85 + 0.15 * e), s * (0.85 + 0.15 * e));
  ctx.translate(-36, -36);
  ctx.globalAlpha *= e;
  ctx.strokeStyle = color;
  ctx.fillStyle = color;
  ctx.lineCap = "round";
  ctx.lineJoin = "round";
  for (const [d, w = 4, fill] of def.ops) {
    const p2 = path(d);
    if (fill) {
      ctx.save();
      ctx.globalAlpha *= fill;
      ctx.fill(p2);
      ctx.restore();
    }
    ctx.lineWidth = w;
    if (fill !== 1) ctx.stroke(p2);
  }
  ctx.restore();
}
